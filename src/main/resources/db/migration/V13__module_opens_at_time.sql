-- Время открытия модуля: opens_at из даты (DATE) становится моментом
-- (TIMESTAMPTZ). Админка задаёт московское время; прежние даты означают
-- «полночь этого дня по Москве».
-- ═══════════════════════════════════════════════════════════════════════

ALTER TABLE course_module
    ALTER COLUMN opens_at TYPE TIMESTAMPTZ
        USING (opens_at::timestamp AT TIME ZONE 'Europe/Moscow');
